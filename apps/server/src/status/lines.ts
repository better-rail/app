/**
 * lines.ts — the Israel Railways line catalogue used by the Service Status endpoint.
 *
 * Israel Railways publishes no official line numbering, so the grouping below
 * follows the community "Line Explorer" map built from the MOT GTFS feed: every
 * train number the feed runs is assigned to one of fourteen marketing lines
 * (e.g. "2" Binyamina – Ashkelon, "34" Karmiel – Be'er Sheva, "7" Herzliya –
 * Jerusalem). Weekend runs reuse the weekday number + 6000/7000 and are listed
 * explicitly as well.
 *
 * `stationIds` is the full ordered corridor of the line (every station any of
 * its trains calls at), as the app's canonical "3700"-style ids, so a trip that
 * carries an unknown train number can still be matched by its stop sequence.
 * The app keeps a display copy of this catalogue in
 * apps/mobile/src/data/rail-lines.ts (ids, badges and colours must stay in sync).
 *
 * Generated from the Line Explorer export — regenerate rather than hand-edit.
 */

export type RailLineId = "1" | "2" | "3" | "3X" | "4" | "5" | "25" | "6" | "7" | "12" | "9" | "10" | "11" | "8"

export type RailLineDefinition = {
  id: RailLineId
  /** The number shown in the line's badge (the catalogue id is not always the public number). */
  badge: string
  color: string
  textColor: string
  badgeStyle: "solid" | "outline"
  name: { he: string; en: string }
  /** Ordered corridor, first terminus to last, as "3700"-style station ids. */
  stationIds: string[]
  /** Every train number known to run on the line (weekday and weekend timetables). */
  trainNumbers: number[]
}

